# Agent CLI Startup Script — gsd
#
# This script is self-contained: it loads .env.local, resolves workspace-local
# AI-tool state directories, runs the sidecar syncs enabled for this workspace
# (backlogit/Engram/kbdb), resolves the Copilot CLI executable, and
# launches it directly in THIS PowerShell host -- no supervising process, no
# process-spawning layer in between. This is deliberate: an intermediate
# process (e.g. a Python launcher) was found to change how many processes are
# attached to the console, which breaks mouse/scroll handling in the launched
# interactive tool. Keeping bootstrap-and-launch native and in-host avoids
# that class of problem entirely.
#
# Usage: ./start.ps1
#
# Auto-MergeInstall / Auto-Tune should come from this workspace's installed
# `.github/agents/` content and the workspace-local GSD distribution. A
# client-level global copy is legacy compatibility state and can shadow newer
# workspace-owned agents; update the workspace harness through its local tuner.
#
# Generated by gsd. Re-run install or tune to regenerate.

$RepoRoot = [IO.Path]::GetFullPath($PSScriptRoot)
$runningOnMacOS = [bool](Get-Variable -Name IsMacOS -ValueOnly -ErrorAction SilentlyContinue)
$directorySeparator = [IO.Path]::DirectorySeparatorChar

if ($directorySeparator -eq '/' -and -not [string]::IsNullOrWhiteSpace($env:PWD)) {
    try {
        $logicalPwd = [IO.Path]::GetFullPath($env:PWD)
        $physicalPwd = & '/bin/sh' -c 'cd -P -- "$1" && pwd -P' -- $logicalPwd 2>$null
        if ($LASTEXITCODE -eq 0 -and $physicalPwd -and
            ([IO.Path]::GetFullPath([string]$physicalPwd).TrimEnd('/', '\') -ceq $RepoRoot.TrimEnd('/', '\'))) {
            $RepoRoot = $logicalPwd
        }
    } catch {
        $logicalPwd = $null
    }
}

function Resolve-TrustedMacAlias {
    param([string]$Path)

    $resolved = $Path
    if ($runningOnMacOS -and $Path -match '^/(tmp|var|etc)(/.*)?$') {
        $topAlias = $matches[1]
        $aliasRest = if ($matches[2]) { $matches[2] } else { '' }
        $topItem = Get-Item -LiteralPath "/$topAlias" -Force -ErrorAction SilentlyContinue
        $rawTarget = $null
        if ($null -ne $topItem -and (($topItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
            if ($null -ne $topItem.PSObject.Properties['LinkTarget'] -and $topItem.LinkTarget) {
                $rawTarget = [string]$topItem.LinkTarget
            } elseif ($null -ne $topItem.Target) {
                $rawTarget = [string]$topItem.Target
            }
        }
        if ($rawTarget -ceq "private/$topAlias" -or $rawTarget -ceq "/private/$topAlias") {
            $resolved = "/private/$topAlias$aliasRest"
        }
    }
    return $resolved
}

$RepoRoot = Resolve-TrustedMacAlias $RepoRoot
$repoRootRoot = [IO.Path]::GetPathRoot($RepoRoot)
$repoRootRelative = $RepoRoot.Substring($repoRootRoot.Length)
$curPrefix = $repoRootRoot
$rootItem = Get-Item -LiteralPath $curPrefix -Force -ErrorAction Stop
if (-not $rootItem.PSIsContainer -or (($rootItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
    Write-Error "Refusing symlink or reparse-point workspace root or ancestor: $curPrefix"
    exit 1
}
foreach ($seg in ($repoRootRelative -split '[/\\]')) {
    if ([string]::IsNullOrWhiteSpace($seg)) { continue }
    $curPrefix = [IO.Path]::Combine($curPrefix, $seg)
    $item = Get-Item -LiteralPath $curPrefix -Force -ErrorAction Stop
    if (-not $item.PSIsContainer -or (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
        Write-Error "Refusing symlink or reparse-point workspace root or ancestor: $curPrefix"
        exit 1
    }
}

# Anchor every child process to the workspace regardless of where this script
# was invoked from.
Set-Location -LiteralPath $PSScriptRoot
# Preferred GSD-managed tools live under <workspace>/.bin. The additional
# .kbdb/.gsd entries are retained compatibility lookup paths; .bin is prepended
# last so it takes highest precedence on PATH.
foreach ($pathEntry in @($PSScriptRoot, (Join-Path $PSScriptRoot ".kbdb\bin"), (Join-Path $PSScriptRoot ".gsd"), (Join-Path $PSScriptRoot ".bin"))) {
    $remainingPath = @($env:PATH -split [IO.Path]::PathSeparator | Where-Object { $_ -and ($_ -ne $pathEntry) })
    $env:PATH = (@($pathEntry) + $remainingPath) -join [IO.Path]::PathSeparator
}

# Load .env.local (gitignored per-developer overrides) if present. Each
# KEY=VALUE line is exported only when that variable is not already set. A
# single pair of matching surrounding quotes is stripped from the value.
$envLocalPath = Join-Path $PSScriptRoot ".env.local"
if ((Test-Path -LiteralPath $envLocalPath -PathType Leaf) -and
    (((Get-Item -LiteralPath $envLocalPath -Force -ErrorAction Stop).Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0)) {
    Get-Content -LiteralPath $envLocalPath | ForEach-Object {
        if ($_ -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$') {
            $name = $matches[1]
            if ($null -eq [Environment]::GetEnvironmentVariable($name, "Process")) {
                $value = $matches[2]
                if ($value.Length -ge 2) {
                    $firstChar = $value[0]
                    $lastChar = $value[$value.Length - 1]
                    if ((($firstChar -eq '"') -or ($firstChar -eq "'")) -and ($lastChar -eq $firstChar)) {
                        $value = $value.Substring(1, $value.Length - 2)
                    }
                }
                [Environment]::SetEnvironmentVariable($name, $value, "Process")
            }
        }
    }
}

$workspaceBinDirectory = Join-Path $PSScriptRoot ".bin"
$env:BUN_INSTALL = Join-Path $workspaceBinDirectory "bun"
$env:BUN_INSTALL_CACHE_DIR = Join-Path $workspaceBinDirectory "bun-cache"
$env:BUN_RUNTIME_TRANSPILER_CACHE_PATH = "0"

$DefaultAgentTempDir = [IO.Path]::Combine($RepoRoot, ".gsd", "runtime", "tmp")
$repoPrefix = $RepoRoot.TrimEnd('\', '/') + $directorySeparator
$pathCmp = if ($directorySeparator -eq '\') { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
$fullTemp = $DefaultAgentTempDir

if (-not [string]::IsNullOrWhiteSpace($env:AGENT_TEMP_DIR)) {
    $rawTemp = [string]$env:AGENT_TEMP_DIR
    $validTemp = $true
    if ($rawTemp -match '[\x00-\x1F]' -or $rawTemp.IndexOf([IO.Path]::PathSeparator) -ge 0 -or
        $rawTemp.IndexOf('*') -ge 0 -or $rawTemp.IndexOf('?') -ge 0 -or $rawTemp.IndexOf('[') -ge 0 -or
        $rawTemp.IndexOf('|') -ge 0 -or $rawTemp.IndexOf('<') -ge 0 -or $rawTemp.IndexOf('>') -ge 0 -or $rawTemp.IndexOf('"') -ge 0 -or
        ($rawTemp -split '[\\/]') -contains '..') {
        $validTemp = $false
    }
    if ($directorySeparator -eq '\') {
        $colonTail = if ($rawTemp -match '^[A-Za-z]:[/\\]') { $rawTemp.Substring(2) } else { $rawTemp }
        if ($colonTail.IndexOf(':') -ge 0) {
            $validTemp = $false
        }
    } elseif ($rawTemp.IndexOf(':') -ge 0) {
        $validTemp = $false
    }

    $candidate = $null
    if ($validTemp) {
        try {
            if ([IO.Path]::IsPathRooted($rawTemp)) {
                $candidate = [IO.Path]::GetFullPath($rawTemp)
            } else {
                $candidate = [IO.Path]::GetFullPath([IO.Path]::Combine($RepoRoot, $rawTemp))
            }
        } catch {
            $candidate = $null
        }
    }
    if ($candidate) {
        $candidate = Resolve-TrustedMacAlias $candidate
    }

    if ($candidate -and $candidate.StartsWith($repoPrefix, $pathCmp)) {
        $relCandidate = $candidate.Substring($repoPrefix.Length).TrimEnd('\', '/')
        $relSlash = $relCandidate.Replace('\', '/')
        if ($relSlash -eq '.git' -or $relSlash.StartsWith('.git/', [StringComparison]::OrdinalIgnoreCase) -or
            (($relCandidate -split '[\\/]') -contains '.git')) {
            $candidate = $null
        }
    } else {
        $candidate = $null
    }

    if ($candidate) {
        $rebasedTemp = $RepoRoot
        $safeExistingSegments = $true
        foreach ($seg in ($relCandidate -split '[\\/]')) {
            if ([string]::IsNullOrWhiteSpace($seg)) { continue }
            $rebasedTemp = [IO.Path]::Combine($rebasedTemp, $seg)
            $segmentItem = Get-Item -LiteralPath $rebasedTemp -Force -ErrorAction SilentlyContinue
            if ($null -ne $segmentItem -and
                ((-not $segmentItem.PSIsContainer) -or (($segmentItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0))) {
                $safeExistingSegments = $false
                break
            }
        }
        if ($safeExistingSegments -and $rebasedTemp.StartsWith($repoPrefix, $pathCmp)) {
            $fullTemp = $rebasedTemp
        }
    }
}
$env:AGENT_TEMP_DIR = $fullTemp

$relTemp = $env:AGENT_TEMP_DIR.Substring($repoPrefix.Length).TrimEnd('\', '/')
$relTempSegments = @($relTemp -split '[\\/]' | Where-Object { $_ })
if ($relTempSegments.Count -eq 0) {
    Write-Error "Refusing invalid AGENT_TEMP_DIR relative path."
    exit 1
}

$currentTempPath = $RepoRoot
foreach ($seg in $relTempSegments) {
    $currentTempPath = [IO.Path]::Combine($currentTempPath, $seg)
    $segmentItem = Get-Item -LiteralPath $currentTempPath -Force -ErrorAction SilentlyContinue
    if ($null -ne $segmentItem -and
        ((-not $segmentItem.PSIsContainer) -or (($segmentItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0))) {
        Write-Error "Refusing symlink or reparse point in AGENT_TEMP_DIR: $currentTempPath"
        exit 1
    }
}

if ($directorySeparator -eq '\') {
    $nativeAssemblyName = [Reflection.AssemblyName]::new("GsdStartupPathPin")
    $nativeAssembly = [Reflection.Emit.AssemblyBuilder]::DefineDynamicAssembly(
        $nativeAssemblyName,
        [Reflection.Emit.AssemblyBuilderAccess]::Run
    )
    $nativeModule = $nativeAssembly.DefineDynamicModule("GsdStartupPathPin")
    $nativeTypeBuilder = $nativeModule.DefineType(
        "GsdStartupPathPin.NativeMethods",
        [Reflection.TypeAttributes]::Public
    )
    $createFileMethod = $nativeTypeBuilder.DefinePInvokeMethod(
        "CreateFileW",
        "kernel32.dll",
        "Public, Static, PinvokeImpl",
        [Reflection.CallingConventions]::Standard,
        [IntPtr],
        [Type[]]@([string], [UInt32], [UInt32], [IntPtr], [UInt32], [UInt32], [IntPtr]),
        [Runtime.InteropServices.CallingConvention]::Winapi,
        [Runtime.InteropServices.CharSet]::Unicode
    )
    $createFileMethod.SetImplementationFlags([Reflection.MethodImplAttributes]::PreserveSig)
    $nativePathMethods = $nativeTypeBuilder.CreateType()
    $pinnedHandles = [System.Collections.Generic.List[Microsoft.Win32.SafeHandles.SafeFileHandle]]::new()
    try {
        $rootRawHandle = $nativePathMethods::CreateFileW(
            $RepoRoot,
            [UInt32]0x80,
            [UInt32]0x3,
            [IntPtr]::Zero,
            [UInt32]3,
            [UInt32]0x02200000,
            [IntPtr]::Zero
        )
        if ($rootRawHandle.ToInt64() -eq -1) {
            throw [System.ComponentModel.Win32Exception]::new([Runtime.InteropServices.Marshal]::GetLastWin32Error())
        }
        $rootHandle = [Microsoft.Win32.SafeHandles.SafeFileHandle]::new($rootRawHandle, $true)
        $pinnedHandles.Add($rootHandle)
        $rootItem = Get-Item -LiteralPath $RepoRoot -Force -ErrorAction Stop
        if (-not $rootItem.PSIsContainer -or (($rootItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
            Write-Error "Refusing symlink or reparse point in workspace root: $RepoRoot"
            exit 1
        }

        foreach ($relativeSegments in @(
            [string[]]@($relTempSegments),
            [string[]]@(".bin"),
            [string[]]@(".bin", "bun-cache")
        )) {
            $createdPath = $RepoRoot
            foreach ($seg in $relativeSegments) {
                $createdPath = [IO.Path]::Combine($createdPath, $seg)
                $null = [IO.Directory]::CreateDirectory($createdPath)
                $childRawHandle = $nativePathMethods::CreateFileW(
                    $createdPath,
                    [UInt32]0x80,
                    [UInt32]0x3,
                    [IntPtr]::Zero,
                    [UInt32]3,
                    [UInt32]0x02200000,
                    [IntPtr]::Zero
                )
                if ($childRawHandle.ToInt64() -eq -1) {
                    throw [System.ComponentModel.Win32Exception]::new([Runtime.InteropServices.Marshal]::GetLastWin32Error())
                }
                $childHandle = [Microsoft.Win32.SafeHandles.SafeFileHandle]::new($childRawHandle, $true)
                $pinnedHandles.Add($childHandle)
                $childItem = Get-Item -LiteralPath $createdPath -Force -ErrorAction Stop
                if (-not $childItem.PSIsContainer -or (($childItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
                    Write-Error "Refusing symlink or reparse point in workspace runtime path: $createdPath"
                    exit 1
                }
            }
        }
    } catch {
        Write-Error "Unable to create workspace runtime directories safely: $_"
        exit 1
    } finally {
        for ($i = $pinnedHandles.Count - 1; $i -ge 0; $i--) {
            $pinnedHandles[$i].Dispose()
        }
    }
} else {
    $posixTempCreation = @'
PATH="$PATH:/bin:/usr/bin"
export PATH
(
    cd -P -- "$1" || exit 1
    expected_prefix="$(pwd -P)"
    [ "$expected_prefix" = "$1" ] || exit 1
    old_ifs="$IFS"
    IFS='/'
    set -- $2
    IFS="$old_ifs"
    for seg do
        [ -n "$seg" ] && [ "$seg" != "." ] && [ "$seg" != ".." ] && [ "$seg" != ".git" ] || exit 1
        [ ! -L "$seg" ] || exit 1
        if [ ! -e "$seg" ]; then
            mkdir -- "$seg" 2>/dev/null || {
                [ -d "$seg" ] && [ ! -L "$seg" ] || exit 1
            }
        fi
        [ ! -L "$seg" ] && [ -d "$seg" ] || exit 1
        cd -P -- "$seg" || exit 1
        expected_prefix="${expected_prefix%/}/$seg"
        [ "$(pwd -P)" = "$expected_prefix" ] || exit 1
    done
)
'@
    & '/bin/sh' -c $posixTempCreation -- $RepoRoot $relTemp
    if ($LASTEXITCODE -ne 0) {
        Write-Error "Refusing symlink or invalid AGENT_TEMP_DIR."
        exit 1
    }
    & '/bin/sh' -c $posixTempCreation -- $RepoRoot ".bin"
    if ($LASTEXITCODE -ne 0) { exit 1 }
    & '/bin/sh' -c $posixTempCreation -- $RepoRoot ".bin/bun-cache"
    if ($LASTEXITCODE -ne 0) { exit 1 }
}

$createdTempPath = $RepoRoot
foreach ($seg in $relTempSegments) {
    $createdTempPath = [IO.Path]::Combine($createdTempPath, $seg)
    $createdItem = Get-Item -LiteralPath $createdTempPath -Force -ErrorAction Stop
    if (-not $createdItem.PSIsContainer -or (($createdItem.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
        Write-Error "Refusing symlink or reparse point in AGENT_TEMP_DIR: $createdTempPath"
        exit 1
    }
}

$env:TEMP = $env:AGENT_TEMP_DIR
$env:TMP = $env:AGENT_TEMP_DIR
$env:TMPDIR = $env:AGENT_TEMP_DIR

$ceilingSep = [IO.Path]::PathSeparator
$ceilingEntries = @(
    if (-not [string]::IsNullOrWhiteSpace($env:GIT_CEILING_DIRECTORIES)) {
        $env:GIT_CEILING_DIRECTORIES -split [regex]::Escape($ceilingSep) | Where-Object { $_ }
    }
)
$ceilingEntries += $env:AGENT_TEMP_DIR

if ($directorySeparator -eq '\') {
    $longRoot = [IO.Path]::GetPathRoot($env:AGENT_TEMP_DIR)
    $longTemp = $longRoot
    $longRelative = $env:AGENT_TEMP_DIR.Substring($longRoot.Length)
    foreach ($seg in ($longRelative -split '[\\/]')) {
        if ([string]::IsNullOrWhiteSpace($seg)) { continue }
        $entries = @()
        try {
            $entries = @([IO.Directory]::GetFileSystemEntries($longTemp, $seg))
        } catch {
            $entries = @()
        }
        if ($entries.Count -gt 0) {
            $longTemp = [IO.Path]::Combine($longTemp, [IO.Path]::GetFileName($entries[0].TrimEnd('\', '/')))
        } else {
            $longTemp = [IO.Path]::Combine($longTemp, $seg)
        }
    }
    if ($longTemp -cne $env:AGENT_TEMP_DIR) {
        $ceilingEntries += $longTemp
    }
}

$deduplicatedCeilings = @()
foreach ($ceilingEntry in $ceilingEntries) {
    if ($deduplicatedCeilings -cnotcontains $ceilingEntry) {
        $deduplicatedCeilings += $ceilingEntry
    }
}
$env:GIT_CEILING_DIRECTORIES = $deduplicatedCeilings -join $ceilingSep

# COPILOT_HOME/ENGRAM_DATA_DIR redirect AI-tool state to workspace-local hidden
# directories so agent memories, checkpoints, and database files are
# git-visible and project-scoped rather than shared across all workspaces.
$env:COPILOT_HOME = if ($env:COPILOT_HOME) { $env:COPILOT_HOME } else { Join-Path $PSScriptRoot ".copilot" }
$env:ENGRAM_DATA_DIR = if ($env:ENGRAM_DATA_DIR) { $env:ENGRAM_DATA_DIR } else { Join-Path $PSScriptRoot ".engram" }
$env:ENGRAM_WORKSPACE = $PSScriptRoot

# GitHub token resolution via `gh`. Non-fatal when `gh` is absent or failing --
# the affected variable is simply left unset. GITHUB_PERSONAL_ACCESS_TOKEN is
# unguarded (always re-resolved when `gh` is available); GITHUB_TOKEN is
# guarded (no-clobber) -- this asymmetry is intentional, matching each
# variable's own conventional precedence.
$ghCmd = Get-Command gh -ErrorAction SilentlyContinue
if ($ghCmd) {
    try {
        $env:GITHUB_PERSONAL_ACCESS_TOKEN = (& $ghCmd.Source auth token 2>$null).Trim()
    } catch {
        Write-Warning "gh auth token failed (non-fatal): $_"
    }
    if (-not $env:GITHUB_TOKEN) {
        try {
            $ghToken = (& $ghCmd.Source auth token 2>$null).Trim()
            if ($ghToken) {
                $env:GITHUB_TOKEN = $ghToken
            }
        } catch {
            Write-Warning "gh auth token failed (non-fatal): $_"
        }
    }
}

# ai_tools.copilot_cli.exe_path from .gsd/config.yaml, when
# explicitly configured to something other than a bare PATH lookup, is
# forwarded as an environment default so the resolution below picks it up
# at the same precedence tier the operator's own environment would.
if (-not $env:COPILOT_EXE_PATH -and -not $env:COPILOT_EXE) {
    $defaultCopilotExe = "copilot"
    if ($defaultCopilotExe -and ($defaultCopilotExe -ne "copilot")) {
        $env:COPILOT_EXE_PATH = $defaultCopilotExe
    }
}

$copilotExe = if ($env:COPILOT_EXE_PATH) {
    $env:COPILOT_EXE_PATH
} elseif ($env:COPILOT_EXE) {
    $env:COPILOT_EXE
} else {
    $copilotCommand = Get-Command "copilot" -ErrorAction SilentlyContinue
    if ($copilotCommand) { $copilotCommand.Source } else { $null }
}

if (-not $copilotExe) {
    Write-Error "Unable to locate Copilot CLI. Set COPILOT_EXE_PATH (or COPILOT_EXE for backward compatibility) or add 'copilot' to PATH."
    exit 1
}

# Sidecar syncs -- derived at install time from the capability packs enabled
# for this workspace (backlogit/agent-engram/kbdb).
$enabledSidecars = @("backlogit", "engram", "kbdb")

$sidecarExecutables = @{
    backlogit = (Join-Path $workspaceBinDirectory "backlogit.exe")
    engram = (Join-Path $workspaceBinDirectory "engram.exe")
    kbdb = (Join-Path $workspaceBinDirectory "kbdb.exe")
}
foreach ($tool in @("backlogit", "engram", "kbdb", "bun", "bunx", "github-mcp-server", "gsd")) {
    $toolExe = Join-Path $workspaceBinDirectory "$tool.exe"
    if (-not (Test-Path -LiteralPath $toolExe -PathType Leaf)) {
        Write-Error "Workspace-local $tool executable is missing: $toolExe. Restore the local runtime before starting; global PATH fallback is disabled."
        exit 1
    }
}
foreach ($entrypoint in @("tools\mcp\node_modules\@upstash\context7-mcp\dist\index.js", "tools\mcp\node_modules\tavily-mcp\build\index.js")) {
    $runtimePath = Join-Path $PSScriptRoot $entrypoint
    if (-not (Test-Path -LiteralPath $runtimePath -PathType Leaf)) {
        Write-Error "Workspace-local MCP runtime is missing: $runtimePath. Run tools\mcp\install.ps1 before starting."
        exit 1
    }
}

if ($enabledSidecars -contains "backlogit") {
    try {
        & $sidecarExecutables.backlogit sync
        if ($LASTEXITCODE -ne 0) {
            throw "backlogit sync failed with exit code $LASTEXITCODE."
        }
    } catch {
        Write-Warning "backlogit sync failed (non-fatal): $_"
    }
}

if ($enabledSidecars -contains "engram") {
    try {
        Write-Host "Synchronizing Engram index -- Direct pre-warm before Copilot startup"
        & $sidecarExecutables.engram --format text sync --timeout 300 --direct
        if ($LASTEXITCODE -ne 0) {
            throw "engram sync failed with exit code $LASTEXITCODE."
        }
    } catch {
        Write-Warning "engram direct pre-warm failed; retrying via daemon sync: $_"
        try {
            & $sidecarExecutables.engram --format text bind
            Write-Host "Synchronizing Engram index -- Daemon-backed pre-warm fallback"
            & $sidecarExecutables.engram --format text sync --timeout 300
            if ($LASTEXITCODE -ne 0) {
                throw "engram sync failed with exit code $LASTEXITCODE."
            }
        } catch {
            Write-Warning "engram sync failed (non-fatal): $_"
        }
    }
}

if (($enabledSidecars -contains "kbdb") -or ($enabledSidecars -contains "graphtor-docs")) {
    try {
        & $sidecarExecutables.kbdb sync
        if ($LASTEXITCODE -ne 0) {
            throw "kbdb sync failed with exit code $LASTEXITCODE."
        }
    } catch {
        Write-Warning "kbdb sync failed (non-fatal): $_"
    }
}

# ai_tools.copilot_cli.args from .gsd/config.yaml -- extra arguments
# always passed before the operator's own argv (e.g. ["--remote"]).
$copilotArguments = @()
$copilotArguments += $args

& $copilotExe @copilotArguments
exit $LASTEXITCODE

